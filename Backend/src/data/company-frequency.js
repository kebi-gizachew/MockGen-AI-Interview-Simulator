// Frequency tier derived from the rank. 1-3 extremely common, 4-10 frequent,
// 11-30 occasional, 31+ rarely reported.
const tierForRank = (rank) => {
  const numeric = Number(rank);
  if (!Number.isFinite(numeric)) return "low";
  if (numeric <= 3) return "very_high";
  if (numeric <= 10) return "high";
  if (numeric <= 30) return "medium";
  return "low";
};

// Stable, deterministic hash so fallback ranks never change between runs
// (keeps seeding idempotent and ordering stable).
const stableHash = (str) => {
  let hash = 0;
  for (let i = 0; i < str.length; i++) {
    hash = (hash * 31 + str.charCodeAt(i)) >>> 0;
  }
  return hash;
};

// Fallback rank for questions not in the curated map: they are real problems
// but less commonly reported at the company, so they rank below every known
// frequent question. Difficulty gives a soft nudge (harder = slightly more
// notable) then a stable hash spreads them deterministically.
const fallbackRank = (question) => {
  const base =
    question.difficulty === "easy" ? 16 : question.difficulty === "hard" ? 24 : 20;
  return base + (stableHash(String(question.title)) % 14);
};

// Full list of companies associated with a seed question: its explicit
// `companies` array (if any) + primary `company` + every additional company in
// MULTI_COMPANY_MAP (deduped, order stable).
const normalizeCompanies = (question) => {
  if (!question) return [];
  const explicit = Array.isArray(question.companies) ? question.companies : [];
  const primary = question.company
    ? String(question.company).trim()
    : explicit[0]
      ? String(explicit[0]).trim()
      : "";
  const extra = MULTI_COMPANY_MAP[question.title] || [];
  const list = [];
  const seen = new Set();
  for (const company of [primary, ...explicit, ...extra]) {
    const name = String(company || "").trim();
    if (name && !seen.has(name)) {
      seen.add(name);
      list.push(name);
    }
  }
  return list;
};

/**
 * Attach company metadata to a seed question:
 *  - companies:            every company that asks this question
 *  - companyFrequencies:   per-company { frequencyRank, interviewFrequency }
 *  - company/frequencyRank/interviewFrequency: primary-company values (kept
 *    for backward compatibility with display + legacy selection logic)
 */
const applyFrequencyMetadata = (question) => {
  const companies = normalizeCompanies(question);
  const companyFrequencies = {};
  for (const company of companies) {
    const rankMap = FREQUENCY_BY_COMPANY[company] || null;
    const rank = (rankMap && rankMap[question.title]) || fallbackRank(question);
    companyFrequencies[company] = {
      frequencyRank: rank,
      interviewFrequency: tierForRank(rank),
    };
  }
  const primary = companies[0] || (question.company ? String(question.company) : "");
  const primaryFreq = companyFrequencies[primary] || null;
  return {
    ...question,
    companies,
    companyFrequencies,
    company: primary || null,
    frequencyRank: primaryFreq ? primaryFreq.frequencyRank : null,
    interviewFrequency: primaryFreq ? primaryFreq.interviewFrequency : null,
  };
};

